const closedMap = () => S.settings().help_closed || {};
const setClosed = (key, on) => S.upsert('settings', { help_closed: { ...closedMap(), [key]: on } }, 'user_id').catch(showError);

export function helpBox(key) {
  const t = HELP[key];
  if (!t) return null;
  if (closedMap()[key]) {
    return h('div', { class: 'help-reopen' }, h('button', { class: 'btn btn-sm help-btn', onClick: () => setClosed(key, false) }, '❓ 이 화면 안내'));
  }
  return h('div', { class: 'help-box' },
    h('div', { class: 'help-head' },
      h('strong', {}, `💡 ${t.title}`),
      h('button', { class: 'btn btn-sm', onClick: () => setClosed(key, true) }, '알겠어요 (접기)')),
    h('ol', {}, t.steps.map((x) => h('li', {}, x))),
    t.tip ? h('p', { class: 'help-tip' }, t.tip) : null);
}
